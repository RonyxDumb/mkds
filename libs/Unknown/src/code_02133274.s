// Unsigned 32-bit division.
//
// Not compiled code: _ll_udiv (code_021329f8.s) calls .L_0213327c, a second entry past the zero check, where a
// compiled function is entered only at its start; the computed jump `add pc, pc, r2, lsl #2` has no bound
// check and lands inside straight-line code, where 1.2 dispatches only switches, through `addls pc` and a
// table of branches; and every step tests the carry of an `adcs` with `sublo`, a condition 1.2 takes only
// from a compare (docs/compiler.md, Conditions).

    .text

// Unsigned 32-bit division: r0 divided by r1 gives the quotient in r0 and the remainder in r1. Division by zero returns
// at once. .L_0213327c skips that check. The dividend is shifted up by the number of leading quotient bits that must be
// zero (found four at a time), then a computed jump enters a run of 32 identical steps at the right place; each step
// shifts the next dividend bit into the remainder and subtracts the divisor when it fits, the carry giving the quotient
// bit.
    .global _u32_div_f
    .type _u32_div_f, @function
_u32_div_f:
    // A zero divisor returns at once.
    cmp r1, #0
    bxeq lr
    // Entry without the zero check. A dividend below the divisor gives quotient 0, remainder the dividend.
    .global .L_0213327c
.L_0213327c:
    cmp r0, r1
    movlo r1, r0
    movlo r0, #0
    bxlo lr
    // r2 = 28 minus the number of leading quotient bits known to be zero, in steps of 4 (16, 8, 4). Shift the dividend
    // up by that many bits, negate the divisor, and jump over the first r2 of the 32 steps below (three instructions
    // each).
    mov r2, #28
    mov r3, r0, lsr #4
    cmp r1, r3, lsr #12
    suble r2, r2, #16
    movle r3, r3, lsr #16
    cmp r1, r3, lsr #4
    suble r2, r2, #8
    movle r3, r3, lsr #8
    cmp r1, r3
    suble r2, r2, #4
    movle r3, r3, lsr #4
    mov r0, r0, lsl r2
    rsb r1, r1, #0
    adds r0, r0, r0
    add r2, r2, r2, lsl #1
    add pc, pc, r2, lsl #2              // pc reads two instructions ahead: step 0 is after the nop
    mov r0, r0                          // never executed
    // The run of division steps; r3 = the remainder, r0 = dividend bits shifted out and quotient bits in.
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    adcs r3, r1, r3, lsl #1
    sublo r3, r3, r1
    adcs r0, r0, r0
    // Remainder to r1.
    mov r1, r3
    bx lr
    .size _u32_div_f, . - _u32_div_f
